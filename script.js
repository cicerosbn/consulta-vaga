function gerarApartamentos() {
  const lista = [];

  // Térreo (1 a 8)
  for (let i = 1; i <= 8; i++) {
    lista.push(i.toString());
  }

  // 1º ao 17º andar (101 a 1708)
  for (let andar = 1; andar <= 17; andar++) {
    for (let f = 1; f <= 8; f++) {
      lista.push(`${andar}${f.toString().padStart(2, "0")}`);
    }
  }

  return lista;
}

